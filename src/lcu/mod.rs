//! Локальный API клиента League of Legends — LCU (League Client Update).
//!
//! Пока клиент League запущен, он поднимает HTTPS-сервер на 127.0.0.1. Через него можно
//! получить те же данные, что и через Riot API (уровень, иконку, ранги — и не только своего
//! аккаунта, но и любого игрока того же сервера), причём без API-ключа и без лимитов.
//!
//! Ограничения:
//! - клиент должен быть запущен, и в нём должен быть выполнен вход;
//! - доступны только игроки того сервера, к которому подключён клиент.
//!
//! Приложение только ЧИТАЕТ данные (GET-запросы). Оно ничего не нажимает в клиенте,
//! не вводит логины и пароли и не запускает игру. Это официально не документированный
//! API: Riot его не поддерживает, но и не запрещает чтение (им пользуются Blitz, Porofessor и др.).
//!
//! Имена союзников в ранговом выборе чемпионов клиент скрывает; вкладка «Лобби» берёт их
//! из чата Riot Client (см. `riot_client`), как программа reveal. Riot такое не одобряет —
//! функция включена по решению владельца, на его риск.

